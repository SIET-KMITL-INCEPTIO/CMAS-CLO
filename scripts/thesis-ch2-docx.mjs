/**
 * รองรับ **ตัวหนา** ในสตริงเดียว โดยไม่ต้องประกอบ TextRun เอง
 */
function runs(text) {
  return text.split(/(\*\*[^*]+\*\*)/).filter(Boolean).map((chunk) => {
    const bold = chunk.startsWith("**") && chunk.endsWith("**")
    return new TextRun({
      text: bold ? chunk.slice(2, -2) : chunk,
      bold,
      font: FONT,
      size: PT(16),
    })
  })
}

