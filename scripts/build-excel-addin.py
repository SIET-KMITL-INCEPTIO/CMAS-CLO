"""Build steps for the CMAS add-in for Excel (app/excel-addin).

    python scripts/build-excel-addin.py text            write src/modCmasText.bas from text/th.json
    python scripts/build-excel-addin.py text --check    exit 1 if modCmasText.bas is out of date
    python scripts/build-excel-addin.py check           static checks on src/ (CI runs this)
    python scripts/build-excel-addin.py package IN.xlam [--out dist/CMAS.xlam]
                                                        add the ribbon to an .xlam built in Excel,
                                                        print its SHA-256 for addin-release.ts

Why a generator: the VBA editor stores a module in the machine's code page, so
Thai written straight into a .bas file turns into question marks on another
locale and on Mac. The generated module holds every string as hex code points
and decodes them with ChrW at run time, which works everywhere.

Why `package`: a ribbon lives in the .xlam's ZIP (customUI/customUI14.xml plus
a relationship), which Excel itself cannot add. The modules are imported by
hand in the VBA editor (README), then this step adds the ribbon.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADDIN = ROOT / "app" / "excel-addin"
TEXT_JSON = ADDIN / "text" / "th.json"
TEXT_BAS = ADDIN / "src" / "modCmasText.bas"
RIBBON_XML = ADDIN / "ribbon" / "customUI14.xml"

RIBBON_PART = "customUI/customUI14.xml"
RIBBON_REL_TYPE = "http://schemas.microsoft.com/office/2007/relationships/ui/extensibility"
KEY = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")
# VBA allows 24 line continuations; 200 hex digits (50 characters) per line keeps
# every line short and allows strings of up to 1,200 characters.
CHUNK = 200


def vba_literal(text: str) -> str:
    """ASCII-only VBA expression that decodes to `text`."""
    hexed = "".join(f"{ord(ch):04X}" for ch in text)
    if any(ord(ch) > 0xFFFF for ch in text):
        raise SystemExit(f"characters outside the BMP are not supported: {text!r}")
    parts = [hexed[i : i + CHUNK] for i in range(0, len(hexed), CHUNK)] or [""]
    if len(parts) > 24:
        raise SystemExit(f"string too long for one VBA statement ({len(text)} characters)")
    return " & _\r\n            ".join(f'U("{p}")' for p in parts)


def render_text_module(strings: dict[str, str]) -> str:
    lines = [
        'Attribute VB_Name = "modCmasText"',
        "' GENERATED by scripts/build-excel-addin.py from app/excel-addin/text/th.json.",
        "' Do not edit: change th.json and run `python scripts/build-excel-addin.py text`.",
        "' Strings are hex code points so this file stays ASCII (see the script's docstring).",
        "Option Explicit",
        "",
        "' T(\"key\", a0, a1): the Thai string for key, with {0} and {1} replaced.",
        "Public Function T(ByVal key As String, Optional ByVal a0 As String = \"\", _",
        "                  Optional ByVal a1 As String = \"\") As String",
        "    Dim s As String",
        "    Select Case key",
    ]
    for key, value in strings.items():
        lines.append(f'    Case "{key}"')
        lines.append(f"        s = {vba_literal(value)}")
    lines += [
        "    Case Else",
        "        s = key",
        "    End Select",
        '    s = Replace(s, "{0}", a0)',
        '    s = Replace(s, "{1}", a1)',
        "    T = s",
        "End Function",
        "",
        "Private Function U(ByVal hexed As String) As String",
        "    Dim i As Long, out As String",
        "    For i = 1 To Len(hexed) Step 4",
        '        out = out & ChrW(CLng("&H" & Mid$(hexed, i, 4)))',
        "    Next i",
        "    U = out",
        "End Function",
        "",
    ]
    text = "\r\n".join(lines)
    text.encode("ascii")  # the whole point: fail here rather than in the VBA editor
    return text


def load_strings() -> dict[str, str]:
    raw = json.loads(TEXT_JSON.read_text(encoding="utf-8"))
    strings = {k: v for k, v in raw.items() if not k.startswith("_")}
    for key, value in strings.items():
        if not KEY.match(key):
            raise SystemExit(f"th.json: key {key!r} is not a plain identifier")
        if not isinstance(value, str):
            raise SystemExit(f"th.json: {key} must be a string")
    return strings


def cmd_text(check: bool) -> int:
    wanted = render_text_module(load_strings())
    current = TEXT_BAS.read_bytes().decode("ascii") if TEXT_BAS.exists() else ""
    if check:
        if current != wanted:
            print(f"{TEXT_BAS.relative_to(ROOT)} is out of date — run: python scripts/build-excel-addin.py text")
            return 1
        print(f"{TEXT_BAS.relative_to(ROOT)} is up to date ({len(load_strings())} strings)")
        return 0
    TEXT_BAS.write_bytes(wanted.encode("ascii"))
    print(f"wrote {TEXT_BAS.relative_to(ROOT)} ({len(load_strings())} strings)")
    return 0


# Nothing compiles VBA outside Excel, so these catch what a reviewer would miss.
FORBIDDEN = [
    (re.compile(r"Scripting\.Dictionary", re.I), "Excel for Mac has no Scripting.Dictionary; use clsCmasMap"),
    (re.compile(r"(^|[^.\w])Shell\s*\(?", re.I), "no Shell: the add-in never runs programs"),
    (re.compile(r"SetOption|IgnoreCert|SslErrorIgnore|Option\(4\)", re.I), "never switch off certificate checks"),
    (re.compile(r"SaveSetting[^\n]*(Token|token)"), "the token must never be written anywhere"),
    # `Put` as a method name failed to compile ("Method or data member not found"):
    # these are VBA file-I/O statements, so never name a Sub, Function or property after one.
    (
        re.compile(
            r"^\s*(?:(?:Public|Private|Friend)\s+)?(?:Static\s+)?(?:Sub|Function|Property\s+(?:Get|Let|Set))\s+"
            r"(?:Put|Get|Open|Close|Print|Write|Input|Seek|Lock|Unlock|Reset|Name|Line|Width)\b",
            re.I,
        ),
        "a procedure named like a VBA statement (Put, Get, Open, Close, ...) does not compile reliably; rename it",
    ),
    (re.compile(r"\bTypeOf\b", re.I), "use TypeName(): TypeOf on a Variant is not portable across VBA versions"),
]
BLOCK_OPEN = re.compile(
    r"^\s*(?:(?:Public|Private|Friend)\s+)?(?:Static\s+)?(Sub|Function|Property\s+(?:Get|Let|Set))\s+\w+",
    re.I,
)
BLOCK_CLOSE = re.compile(r"^\s*End\s+(Sub|Function|Property)\b", re.I)


def check_content_type() -> list[str]:
    """Content-Type must only be set together with a body.

    A JSON Content-Type with an empty body is a 400 from the server, which
    failed POST /excel/device, the first call of every sign-in. app.inject()
    in the server's tests never sends the header without a body, so only this
    check and a real client notice.
    """
    problems: list[str] = []
    http = ADDIN / "src" / "modCmasHttp.bas"
    lines = http.read_bytes().decode("ascii").split("\r\n")
    for n, line in enumerate(lines):
        if "SetRequestHeader" in line and "Content-Type" in line and not line.lstrip().startswith("'"):
            guard = next((l for l in reversed(lines[:n]) if re.match(r"^\s*(If|Else|ElseIf)\b", l)), "")
            if not re.match(r"^\s*If Len\(body\) > 0 Then\s*$", guard):
                problems.append(f"{http.relative_to(ROOT).as_posix()}:{n + 1}: Content-Type is set without a body; set it inside `If Len(body) > 0 Then`")
    mac = ADDIN / "mac" / "CMAS.applescript"
    inside = False
    for n, line in enumerate(mac.read_text("utf-8").splitlines()):
        s = line.strip()
        if re.match(r'^if theBody is not "" then$', s):
            inside = True
        elif s == "end if":
            inside = False
        elif "Content-Type" in s and not s.startswith("--") and not inside:
            problems.append(f"{mac.relative_to(ROOT).as_posix()}:{n + 1}: Content-Type is set without a body; set it inside `if theBody is not \"\" then`")
    return problems


def check_sources() -> list[str]:
    problems: list[str] = check_content_type()
    files = sorted((ADDIN / "src").glob("*.bas")) + sorted((ADDIN / "src").glob("*.cls"))
    names: set[str] = set()
    for path in files:
        raw = path.read_bytes()
        rel = path.relative_to(ROOT).as_posix()
        try:
            text = raw.decode("ascii")
        except UnicodeDecodeError:
            problems.append(f"{rel}: not ASCII (Thai belongs in text/th.json)")
            continue
        if b"\n" in raw.replace(b"\r\n", b""):
            problems.append(f"{rel}: LF line endings (the VBA editor's Import needs CRLF)")
        m = re.search(r'^Attribute VB_Name = "(\w+)"', text, re.M)
        if not m or m.group(1) != path.stem:
            problems.append(f"{rel}: VB_Name does not match the file name")
        elif m.group(1) in names:
            problems.append(f"{rel}: duplicate module name")
        else:
            names.add(m.group(1))
        depth = 0
        for n, line in enumerate(text.split("\r\n"), 1):
            code = line.split("'", 1)[0] if '"' not in line else line
            if BLOCK_OPEN.match(code) and not re.match(r"^\s*(?:Public|Private)?\s*Declare\b", code, re.I):
                depth += 1
                if depth > 1:
                    problems.append(f"{rel}:{n}: a procedure starts inside another")
            elif BLOCK_CLOSE.match(code):
                depth -= 1
                if depth < 0:
                    problems.append(f"{rel}:{n}: End without a procedure")
                    depth = 0
            for pattern, why in FORBIDDEN:
                if not line.lstrip().startswith("'") and pattern.search(line):
                    problems.append(f"{rel}:{n}: {why}")
        if depth != 0:
            problems.append(f"{rel}: a procedure is never closed")
    if render_text_module(load_strings()) != (TEXT_BAS.read_bytes().decode("ascii") if TEXT_BAS.exists() else ""):
        problems.append("src/modCmasText.bas is out of date: python scripts/build-excel-addin.py text")
    return problems


def cmd_check() -> int:
    problems = check_sources()
    for p in problems:
        print("✗", p)
    if problems:
        return 1
    print("excel add-in sources: ASCII, CRLF, names, procedures, forbidden calls, text module — ok")
    return 0


def add_ribbon_relationship(rels: str) -> str:
    if RIBBON_REL_TYPE in rels:
        return rels
    rel = f'<Relationship Id="cmasRibbon" Type="{RIBBON_REL_TYPE}" Target="{RIBBON_PART}"/>'
    if "</Relationships>" not in rels:
        raise SystemExit("_rels/.rels has no </Relationships>: not an Office file")
    return rels.replace("</Relationships>", rel + "</Relationships>")


def package(src: Path, out: Path) -> str:
    """Copy `src` to `out` with the ribbon added. Returns the SHA-256 of `out`."""
    with zipfile.ZipFile(src) as zin:
        names = zin.namelist()
        if "xl/vbaProject.bin" not in names:
            raise SystemExit(f"{src} has no VBA project — import the modules in Excel first")
        if "_rels/.rels" not in names:
            raise SystemExit(f"{src} is not an Office file")
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zout:
            for info in zin.infolist():
                if info.filename == RIBBON_PART:
                    continue  # replaced below
                data = zin.read(info.filename)
                if info.filename == "_rels/.rels":
                    data = add_ribbon_relationship(data.decode("utf-8")).encode("utf-8")
                zout.writestr(info, data)
            zout.writestr(RIBBON_PART, RIBBON_XML.read_bytes())
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(buf.getvalue())
    return hashlib.sha256(out.read_bytes()).hexdigest()


def cmd_package(src: Path, out: Path) -> int:
    if not src.exists():
        raise SystemExit(f"{src} not found")
    if src.resolve() == out.resolve():
        shutil.copyfile(src, src.with_suffix(".orig.xlam"))
    digest = package(src, out)
    print(f"wrote {out}")
    print(f"sha256 {digest}")
    print("next: put this sha256 and the version in app/server/src/modules/excel/addin-release.ts")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("text")
    t.add_argument("--check", action="store_true")
    sub.add_parser("check")
    p = sub.add_parser("package")
    p.add_argument("xlam", type=Path)
    p.add_argument("--out", type=Path, default=ADDIN / "dist" / "CMAS.xlam")
    args = parser.parse_args()
    if args.cmd == "text":
        return cmd_text(args.check)
    if args.cmd == "check":
        return cmd_check()
    return cmd_package(args.xlam, args.out)


if __name__ == "__main__":
    sys.exit(main())
